// Writes the default content document as a module the edge function can import.
// Run: npm run gen:defaults (after editing src/data/*).
import { writeFileSync } from 'node:fs'
import { DEFAULT_CONTENT } from '../src/data/defaults.js'

const out = 'supabase/functions/_shared/default-content.js' // run from the project root
writeFileSync(out, `// Generated by scripts/gen-defaults.mjs from src/data. Do not edit by hand.\nexport default ${JSON.stringify(DEFAULT_CONTENT, null, 1)}\n`)
console.log('wrote', out)
